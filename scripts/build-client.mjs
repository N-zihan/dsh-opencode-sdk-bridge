/**
 * Build lib/client.js from src/client/index.js.
 *
 * Wraps the authored CJS body into the host's module-loader factory shape —
 * exactly the contract dsh-opencode-xdbridge uses (verified against this
 * profile's installed copy).
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = path.resolve(process.argv[2] ?? '.')
const source = path.join(root, 'src', 'client', 'index.js')
const target = path.join(root, 'lib', 'client.js')
const id = 'dsh-opencode-sdk-bridge'

const body = readFileSync(source, 'utf8')
const banner = `// Generated by scripts/build-client.mjs — edit src/client/index.js instead.\n`
const wrapped = `${banner}window.__ModuleLoader__.load({\n  id: ${JSON.stringify(id)},\n  factory: (require) => {\n    var module = { exports: {} };\n    var exports = module.exports;\n${body
  .split('\n')
  .map(line => `    ${line}`)
  .join('\n')}\n    return module.exports;\n  },\n});\n`

mkdirSync(path.dirname(target), { recursive: true })
writeFileSync(target, wrapped, 'utf8')
console.log(`wrote ${path.relative(root, target)}`)
